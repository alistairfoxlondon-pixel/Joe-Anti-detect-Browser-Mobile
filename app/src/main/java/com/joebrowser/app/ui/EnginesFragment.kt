package com.joebrowser.app.ui

import android.content.BroadcastReceiver
import android.content.Context
import android.content.Intent
import android.content.res.ColorStateList
import android.graphics.Typeface
import android.os.Bundle
import android.view.Gravity
import android.view.LayoutInflater
import android.view.View
import android.view.ViewGroup
import android.widget.LinearLayout
import android.widget.TextView
import androidx.core.content.ContextCompat
import androidx.fragment.app.Fragment
import com.google.android.material.button.MaterialButton
import com.joebrowser.app.AppEvents
import com.joebrowser.app.R
import com.joebrowser.app.data.BrowserEngine
import com.joebrowser.app.data.ProfileRepository
import com.joebrowser.app.databinding.FragmentEnginesBinding
import com.joebrowser.app.fingerprint.FingerprintFactory

/**
 * Engine catalogue.
 *
 * Each card is generated by [buildEngineCard] so all five share one layout definition: title,
 * engine family + usage count, the pinned build list, and a create action. The card never
 * shows a paragraph — only the one honest note that applies to Gecko identities.
 */
class EnginesFragment : Fragment(), MainActivity.Refreshable {

    private var _binding: FragmentEnginesBinding? = null
    private val binding get() = _binding!!
    private var usage: Map<BrowserEngine, Int> = emptyMap()

    /**
     * The usage badges say how many profiles run each engine, so this screen has to react when
     * a profile is created, edited or deleted elsewhere — otherwise it kept the count it read
     * when the tab was first opened.
     */
    private val receiver = object : BroadcastReceiver() {
        override fun onReceive(context: Context?, intent: Intent?) {
            if (intent?.action == AppEvents.ACTION_DATA_CHANGED) refresh()
        }
    }

    override fun onCreateView(inflater: LayoutInflater, container: ViewGroup?, savedInstanceState: Bundle?): View {
        _binding = FragmentEnginesBinding.inflate(inflater, container, false)
        return binding.root
    }

    override fun onViewCreated(view: View, savedInstanceState: Bundle?) {
        render()
    }

    override fun onStart() {
        super.onStart()
        AppEvents.register(requireContext().applicationContext, receiver, listOf(AppEvents.ACTION_DATA_CHANGED))
    }

    override fun onStop() {
        AppEvents.unregister(requireContext().applicationContext, receiver)
        super.onStop()
    }

    override fun onResume() {
        super.onResume()
        refresh()
    }

    override fun refresh() {
        if (_binding == null) return
        ProfileRepository.profiles(requireContext().applicationContext) { profiles ->
            if (_binding == null) return@profiles
            usage = BrowserEngine.entries.associateWith { engine ->
                profiles.count { it.engine == engine }
            }
            render()
        }
    }

    private fun render() {
        val container = binding.engineContainer
        container.removeAllViews()
        BrowserEngine.entries.forEach { engine ->
            container.addView(buildEngineCard(engine, usage[engine] ?: 0))
        }
    }

    private fun buildEngineCard(engine: BrowserEngine, usedBy: Int): View {
        val context = requireContext()
        val density = resources.displayMetrics.density
        fun dp(value: Int): Int = (value * density).toInt()

        val card = LinearLayout(context).apply {
            orientation = LinearLayout.VERTICAL
            background = ContextCompat.getDrawable(context, R.drawable.bg_card)
            setPadding(dp(12), dp(12), dp(12), dp(12))
            layoutParams = LinearLayout.LayoutParams(
                LinearLayout.LayoutParams.MATCH_PARENT,
                LinearLayout.LayoutParams.WRAP_CONTENT
            ).apply { bottomMargin = dp(10) }
        }

        // Row 1: official brand mark + name + usage chip
        val titleRow = LinearLayout(context).apply {
            orientation = LinearLayout.HORIZONTAL
            gravity = Gravity.CENTER_VERTICAL
        }
        titleRow.addView(android.widget.ImageView(context).apply {
            setImageResource(brandLogoRes(engine))
            layoutParams = LinearLayout.LayoutParams(dp(32), dp(32)).apply { marginEnd = dp(12) }
            contentDescription = null
        })
        titleRow.addView(TextView(context).apply {
            text = engine.title
            setTextAppearance(R.style.Text_Jb_CardTitle)
            layoutParams = LinearLayout.LayoutParams(0, LinearLayout.LayoutParams.WRAP_CONTENT, 1f)
            maxLines = 1
            ellipsize = android.text.TextUtils.TruncateAt.END
        })
        titleRow.addView(TextView(context).apply {
            text = if (usedBy > 0) getString(R.string.engines_used_by, usedBy)
            else getString(R.string.engines_unused)
            textSize = 10f
            setTypeface(typeface, Typeface.BOLD)
            setTextColor(ContextCompat.getColor(context, if (usedBy > 0) R.color.accent else R.color.text_muted))
            setBackgroundResource(R.drawable.bg_chip_neutral)
            setPadding(dp(7), dp(3), dp(7), dp(3))
        })
        card.addView(titleRow)

        // Row 2: pinned builds (mono, inset, single line)
        card.addView(TextView(context).apply {
            text = FingerprintFactory.buildsFor(engine).take(3).joinToString(" · ")
            textSize = 11f
            typeface = Typeface.MONOSPACE
            setTextColor(ContextCompat.getColor(context, R.color.text_dim))
            setBackgroundResource(R.drawable.bg_card_inset)
            setPadding(dp(8), dp(6), dp(8), dp(6))
            maxLines = 1
            ellipsize = android.text.TextUtils.TruncateAt.END
            layoutParams = LinearLayout.LayoutParams(
                LinearLayout.LayoutParams.MATCH_PARENT,
                LinearLayout.LayoutParams.WRAP_CONTENT
            ).apply { topMargin = dp(9) }
        })

        if (engine == BrowserEngine.FIREFOX) {
            card.addView(TextView(context).apply {
                setText(R.string.engines_firefox_note)
                textSize = 10.5f
                setTextColor(ContextCompat.getColor(context, R.color.warning))
                setPadding(0, dp(7), 0, 0)
                maxLines = 1
                ellipsize = android.text.TextUtils.TruncateAt.END
            })
        }

        card.addView(MaterialButton(
            context, null, com.google.android.material.R.attr.materialButtonOutlinedStyle
        ).apply {
            setText(R.string.profiles_new)
            textSize = 12.5f
            isAllCaps = false
            minHeight = dp(44)
            setTextColor(ContextCompat.getColor(context, R.color.text))
            strokeColor = ColorStateList.valueOf(ContextCompat.getColor(context, R.color.line))
            strokeWidth = dp(1)
            cornerRadius = dp(10)
            icon = ContextCompat.getDrawable(context, R.drawable.ic_plus)
            iconTint = ColorStateList.valueOf(ContextCompat.getColor(context, R.color.accent))
            iconSize = dp(16)
            iconPadding = dp(8)
            setOnClickListener {
                ProfileEditorActivity.launchForEngine(requireContext(), engine)
            }
            layoutParams = LinearLayout.LayoutParams(
                LinearLayout.LayoutParams.MATCH_PARENT, dp(44)
            ).apply { topMargin = dp(10) }
        })

        return card
    }

    private fun brandLogoRes(engine: BrowserEngine): Int = when (engine) {
        BrowserEngine.CHROME -> R.drawable.logo_chrome
        BrowserEngine.CHROMIUM -> R.drawable.logo_chromium
        BrowserEngine.BRAVE -> R.drawable.logo_brave
        BrowserEngine.EDGE -> R.drawable.logo_edge
        BrowserEngine.FIREFOX -> R.drawable.logo_firefox
    }

    override fun onDestroyView() {
        _binding = null
        super.onDestroyView()
    }
}
